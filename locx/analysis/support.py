"""Support process: how much literature backs each assertion (graph urn:locx:graph:support), from our data only.
Generated by its own activity (a locx:SupportComputation, locx:supportRun/<time>), separate from the GOA comparison.

  python -m locx.analysis.support [--run-id ID] [--replace]

Per assertion:
  locx:support/<key>        a locx:Support: claim, paper and author-group counts, papers stating it as finding /
                            background / hedged, opposing papers, journals, citations, years, context-dependent
  locx:authorGroup/<key>/gN a locx:AuthorGroup: the backing papers whose authors overlap
Author groups: two backing papers are in the same group when they share a person. People are OpenAlex authors
(papers graph); persons the reasoner merged (owl:sameAs in the inferred graph, from a shared ORCID) count as one.
Groups are connected components over the papers of ONE assertion. Writes data/interim/support_stats.jsonl (read by
verdicts.py for its reports) and reports/support.json.
"""
import argparse
import json
import sys
import time
from collections import Counter, defaultdict
from datetime import datetime, timezone

from locx import ontology as O
from locx.config import CFG, DATA, INTERIM, RDF, REPORTS
from locx.io import read_jsonl, write_jsonl
from locx.kg import fuseki
from locx.kg.ttl import LOCX, lit

G = CFG["graphs"]
S = G["support"]
RUNS = DATA / "runs"


def akey(cl) -> str:
    return f"{cl['protein']['uniprot']}_{cl['location']['go_id'].replace(':', '_')}_{cl['polarity']}"


def integer(x) -> str:
    return f'"{int(x)}"^^xsd:integer'


def paper_people() -> dict[str, set]:
    """PMID -> canonical person IRIs (OpenAlex authors; owl:sameAs merges from the inferred graph)."""
    same = defaultdict(set)
    for r in fuseki.select(f"""PREFIX owl: <http://www.w3.org/2002/07/owl#>
        SELECT ?a ?b WHERE {{ GRAPH <{G['inferred']}> {{ ?a owl:sameAs ?b FILTER (?a != ?b) }} }}"""):
        same[r["a"]].add(r["b"])
    canon = {}
    for a, bs in same.items():   # sameAs is symmetric and transitive in the closure: the smallest IRI names the set
        canon[a] = min({a} | bs)
    out = defaultdict(set)
    for r in fuseki.select(f"""PREFIX locx: <{LOCX}>
        SELECT ?paper ?person WHERE {{ GRAPH <{G['papers']}> {{ ?paper locx:hasAuthorship/locx:author ?person }} }}"""):
        out[r["paper"].rsplit("/", 1)[-1]].add(canon.get(r["person"], r["person"]))
    return out, sum(len(b) for b in same.values()) // 2


def groups(pmids, people) -> tuple[dict, dict]:
    """({pmid: group 1..k}, {group: persons shared by two or more of its papers}); groups numbered by earliest PMID."""
    pmids = sorted(set(pmids), key=int)
    parent = {p: p for p in pmids}

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x
    by_person = defaultdict(list)
    for p in pmids:
        for person in people.get(p, ()):
            by_person[person].append(p)
    for ps in by_person.values():
        for q in ps[1:]:
            parent[find(q)] = find(ps[0])
    roots, out = {}, {}
    for p in pmids:
        out[p] = roots.setdefault(find(p), len(roots) + 1)
    linked = defaultdict(set)
    for person, ps in by_person.items():
        if len(ps) > 1:
            linked[out[ps[0]]].add(person)
    return out, linked


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run-id", default=CFG["extract"]["main_run"])
    ap.add_argument("--replace", action="store_true")
    a = ap.parse_args()
    for t in ("locx:Support", "locx:AuthorGroup", "locx:SupportComputation", "locx:about", "locx:includesPaper", "locx:linkedBy",
              "locx:contextDependent", "locx:nClaims"):
        O.term(t)
    t0 = time.time()
    n = fuseki.count(S)
    if n and not a.replace:
        sys.exit(f"[support] {S} already has {n} triples; rerun with --replace to rebuild it")
    claims = [c for c in read_jsonl(RUNS / a.run_id / "claims_final.jsonl") if c["valid"]]
    papers = {p["pmid"]: p for p in read_jsonl(INTERIM / "papers.jsonl")}
    records = json.loads((INTERIM / "epmc_records.json").read_text())
    people, n_same = paper_people()
    by_a = defaultdict(list)
    for c in claims:
        by_a[akey(c)].append(c)
    pt_papers = defaultdict(set)   # (protein, GO, polarity) -> PMIDs
    for c in claims:
        pt_papers[(c["protein"]["uniprot"], c["location"]["go_id"], c["polarity"])].add(c["pmid"])
    started = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S")
    act = f"<{LOCX}supportRun/{started.replace(':', '')}>"
    ttl = ["@prefix locx: <http://example.org/locx/> .\n@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .\n"
           "@prefix prov: <http://www.w3.org/ns/prov#> .\n@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .\n"
           "@prefix pubmed: <https://pubmed.ncbi.nlm.nih.gov/> .\n"]
    stats, n_groups_total = [], 0
    for k, cs in sorted(by_a.items()):
        pm = sorted({c["pmid"] for c in cs}, key=int)
        g, linked = groups(pm, people)
        c0 = cs[0]
        opp = "absent" if c0["polarity"] == "present" else "present"
        years = [papers[p]["year"] for p in pm if papers[p].get("year")]
        journals = {((records.get(p) or {}).get("journal") or {}).get("nlmid") for p in pm} - {None}
        s = {"assertion": k, "symbol": c0["protein"]["symbol"], "uniprot": c0["protein"]["uniprot"],
             "go_id": c0["location"]["go_id"], "location": c0["location"]["label"], "polarity": c0["polarity"],
             "n_claims": len(cs), "n_papers": len(pm), "n_groups": len(set(g.values())),
             "n_papers_finding": len({c["pmid"] for c in cs if c["source_type"] == "finding"}),
             "n_papers_background": len({c["pmid"] for c in cs if c["source_type"] == "background"}),
             "n_papers_hedged": len({c["pmid"] for c in cs if c["certainty"] == "hedged"}),
             "context": any(c["conditions"] for c in cs),
             "year_first": min(years) if years else None, "year_last": max(years) if years else None,
             "n_journals": len(journals), "sum_citations": sum(papers[p].get("cited_by") or 0 for p in pm),
             "methods": sorted({c["method"] for c in cs} - {"not_stated"}),
             "organisms": sorted({c["organism"] for c in cs} - {"not_stated"}),
             "conditions": list(dict.fromkeys(x for c in cs for x in c["conditions"]))[:5],
             "n_opposing_papers": len(pt_papers.get((c0["protein"]["uniprot"], c0["location"]["go_id"], opp), set())),
             "tiers": sorted({t for c in cs for t in c["tiers"]}), "pmids": pm,
             "example": {"pmid": c0["pmid"], "sentence": c0["sentence_text"]}}
        stats.append(s)
        a_iri = f"<{LOCX}assertion/{k}>"
        ttl.append(f"<{LOCX}support/{k}> a locx:Support ; locx:about {a_iri} ; prov:wasGeneratedBy {act} ; "
                   f"locx:nClaims {integer(s['n_claims'])} ; locx:nPapers {integer(s['n_papers'])} ; "
                   f"locx:nGroups {integer(s['n_groups'])} ; locx:nPapersFinding {integer(s['n_papers_finding'])} ; "
                   f"locx:nPapersBackground {integer(s['n_papers_background'])} ; "
                   f"locx:nPapersHedged {integer(s['n_papers_hedged'])} ; "
                   f"locx:nOpposingPapers {integer(s['n_opposing_papers'])} ; locx:nJournals {integer(s['n_journals'])} ; "
                   f"locx:sumCitations {integer(s['sum_citations'])} ; "
                   + (f"locx:yearFirst {integer(s['year_first'])} ; locx:yearLast {integer(s['year_last'])} ; " if years else "")
                   + f"locx:contextDependent {'true' if s['context'] else 'false'} .")
        for gi in sorted(set(g.values())):
            members = [p for p in pm if g[p] == gi]
            ttl.append(f"<{LOCX}authorGroup/{k}/g{gi}> a locx:AuthorGroup ; locx:about {a_iri} ; "
                       f"prov:wasGeneratedBy {act} ; "
                       + " ; ".join([f"locx:includesPaper pubmed:{p}" for p in members]
                                    + [f"locx:linkedBy <{x}>" for x in sorted(linked.get(gi, ()))]) + " .")
            n_groups_total += 1
    ended = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S")
    ttl.append(f"{act} a locx:SupportComputation ; rdfs:label {lit('support computation')} ; "
               f"rdfs:comment {lit('Claim, paper and independent author-group counts per assertion, from our graphs only (locx/analysis/support.py). Same group = a shared person (OpenAlex author; reasoner-merged when they share an ORCID).')} ; "
               f"prov:used <{LOCX}run/{a.run_id}> , <{LOCX}ontology> ; "
               f'prov:startedAtTime "{started}"^^xsd:dateTime ; prov:endedAtTime "{ended}"^^xsd:dateTime .')
    path = RDF / f"support_{a.run_id}.ttl"
    path.write_text("\n".join(ttl) + "\n")
    nt = fuseki.load(S, path, replace=a.replace)
    write_jsonl(INTERIM / "support_stats.jsonl", stats)
    out = {"run_id": a.run_id, "assertions": len(stats), "author_groups": n_groups_total,
           "persons_merged_by_reasoner": n_same, "context_dependent": sum(s["context"] for s in stats),
           "by_n_groups": dict(sorted(Counter(min(s["n_groups"], 5) for s in stats).items())),
           "triples": nt, "seconds": round(time.time() - t0)}
    (REPORTS / "support.json").write_text(json.dumps(out, indent=1))
    print(f"[support] {len(stats)} assertions, {n_groups_total} author groups, {n_same} person merges from the "
          f"reasoner; {S}: {nt} triples ({out['seconds']} s) -> reports/support.json")


if __name__ == "__main__":
    main()
